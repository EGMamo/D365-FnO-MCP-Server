import { describe, expect, it } from 'vitest';
import { parse } from 'dotenv';
import { quoteEnvValue, renderEnvFile } from '../src/cli/envFile.js';

const HEADER = '# Generated by `d365-fno-mcp-server setup`';

/** The value `dotenv` reads back for `key` after `renderEnvFile` wrote it. */
function readBack(value: string, key = 'KEY'): string | undefined {
  return parse(renderEnvFile(HEADER, [[key, value]]))[key];
}

describe('quoteEnvValue', () => {
  it.each([
    ['plain', 'abc'],
    ['a Windows path', 'K:\\AosService\\PackagesLocalDirectory'],
    ['a path with an inner space', 'C:\\Users\\Jo Smith\\Metadata'],
    ['a value with an equals sign', 'a=b'],
    ['a value with dollar signs', 'pa$$word'],
    ['a backslash-n path', 'C:\\new\\Models'],
    ['an apostrophe inside', "it's"],
    ['an empty value', ''],
  ])('leaves %s unquoted', (_label, value) => {
    expect(quoteEnvValue(value)).toBe(value);
  });

  it.each([
    ['a hash', 'abc#def', "'abc#def'"],
    ['a hash after a space', 'C:\\Repos\\Models #2\\Custom', "'C:\\Repos\\Models #2\\Custom'"],
    ['a URL fragment', 'https://h.example.com/mcp#frag', "'https://h.example.com/mcp#frag'"],
    ['leading whitespace', ' lead', "' lead'"],
    ['trailing whitespace', 'trail ', "'trail '"],
    ['a leading double quote', '"quoted"', `'"quoted"'`],
    ['a leading single quote', "'quoted'", "`'quoted'`"],
    ['a leading backtick', '`bt`', "'`bt`'"],
  ])('quotes %s', (_label, value, expected) => {
    expect(quoteEnvValue(value)).toBe(expected);
  });

  it('uses backticks for a value that needs quoting and holds a single quote', () => {
    expect(quoteEnvValue("it's #1")).toBe("`it's #1`");
  });

  it('cannot represent a value holding every quote character', () => {
    expect(quoteEnvValue("it's `#1`")).toBeNull();
  });

  it('cannot represent a value that needs quoting and ends in a backslash', () => {
    // dotenv reads the closing quote of 'C:\Models #2\' as escaped and runs into the next line.
    expect(quoteEnvValue('C:\\Models #2\\')).toBeNull();
  });

  it('keeps a trailing backslash when the value needs no quoting', () => {
    expect(quoteEnvValue('K:\\AosService\\')).toBe('K:\\AosService\\');
  });

  it('does not let a quoted value ending in a backslash swallow the entry after it', () => {
    const text = renderEnvFile(HEADER, [
      ['A', 'K:\\AosService\\'],
      ['B', '#.an n'],
    ]);
    expect(parse(text)).toMatchObject({ A: 'K:\\AosService\\', B: '#.an n' });
  });

  it.each([
    ['a newline', 'a\nb'],
    ['a carriage return', 'a\rb'],
    ['a tab', 'a\tb'],
    ['a NUL', 'a\u0000b'],
    ['a line separator', 'a\u2028b'],
  ])(
    'cannot represent %s',
    (_label, value) => {
      expect(quoteEnvValue(value)).toBeNull();
    }
  );
});

describe('renderEnvFile', () => {
  it.each([
    'abc',
    'K:\\AosService\\PackagesLocalDirectory',
    'C:\\Users\\Jo Smith\\Models #2',
    'abc#def',
    ' lead and trail ',
    '"double"',
    "'single'",
    '`tick`',
    "it's #1",
    'C:\\new\\Models',
    'pa$$word=1',
    'https://h.example.com/mcp#frag',
    '',
  ])('reads back %j exactly through dotenv', (value) => {
    expect(readBack(value)).toBe(value);
  });

  it('writes the header, one line per entry in order, and a final newline', () => {
    const text = renderEnvFile(HEADER, [
      ['MCP_TRANSPORT', 'http'],
      ['D365_PACKAGES_DIR', 'C:\\Users\\Jo Smith\\Models #2'],
    ]);
    expect(text).toBe(
      `${HEADER}\nMCP_TRANSPORT=http\nD365_PACKAGES_DIR='C:\\Users\\Jo Smith\\Models #2'\n`
    );
  });

  it('reads every entry back from a multi-entry file', () => {
    const entries: Array<readonly [string, string]> = [
      ['MCP_API_KEY', 'a'.repeat(40)],
      ['D365_CUSTOM_METADATA_DIR', 'C:\\Repos\\Models #2\\Custom'],
      ['D365_HOSTED_MCP_URL', 'https://h.example.com/mcp'],
    ];
    const parsed = parse(renderEnvFile(HEADER, entries));
    for (const [key, value] of entries) expect(parsed[key]).toBe(value);
  });

  it('refuses a value it cannot write, naming the key but not the value', () => {
    const secret = "s3cr3t-with-'both`-quotes #";
    let message = '';
    try {
      renderEnvFile(HEADER, [['MCP_API_KEY', secret]]);
    } catch (error) {
      message = error instanceof Error ? error.message : String(error);
    }
    expect(message).toContain('MCP_API_KEY');
    expect(message).not.toContain(secret);
  });
});
