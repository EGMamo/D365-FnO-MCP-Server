import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';
import fs from 'fs';
import os from 'os';
import path from 'path';
import { fileURLToPath } from 'url';
import { parse } from 'dotenv';
import { gatewayConfigSchema } from '../src/gateway/config.js';
import { parseSetupFlags, setupCommand, type SetupOptions } from '../src/cli/setup.js';

const fixturesDir = path.join(path.dirname(fileURLToPath(import.meta.url)), 'fixtures');
const API_KEY = 'k'.repeat(40);
const HOSTED_URL = 'https://hosted.example.com/mcp';
const HOSTED_KEY = 'hosted-key-0123456789-abcdef';

describe('parseSetupFlags', () => {
  it('maps every flag to its option', () => {
    const parsed = parseSetupFlags({
      'non-interactive': true,
      mode: 'hosted',
      'packages-dir': '/p',
      'api-key': 'key',
      'db-path': './db',
      transport: 'http',
      host: '127.0.0.1',
      'hosted-url': HOSTED_URL,
      'hosted-api-key': 'hk',
      'hosted-api-key-file': '/k',
      'custom-dir': '/c',
      force: true,
    });

    expect(parsed).toEqual({
      options: {
        nonInteractive: true,
        mode: 'hosted',
        packagesDir: '/p',
        apiKey: 'key',
        dbPath: './db',
        transport: 'http',
        host: '127.0.0.1',
        hostedUrl: HOSTED_URL,
        hostedApiKey: 'hk',
        hostedApiKeyFile: '/k',
        customDir: '/c',
        force: true,
      },
    });
  });

  it('is interactive and leaves everything unset without flags', () => {
    expect(parseSetupFlags({})).toEqual({
      options: {
        nonInteractive: false,
        mode: undefined,
        packagesDir: undefined,
        apiKey: undefined,
        dbPath: undefined,
        transport: undefined,
        host: undefined,
        hostedUrl: undefined,
        hostedApiKey: undefined,
        hostedApiKeyFile: undefined,
        customDir: undefined,
        force: false,
      },
    });
  });

  it.each([
    [{ 'non-interactive': true }, true],
    [{ 'non-interactive': 'true' }, true],
    [{ 'non-interactive': 'false' }, false],
  ])('reads --non-interactive from %j', (flags, expected) => {
    const parsed = parseSetupFlags(flags);
    expect('options' in parsed && parsed.options.nonInteractive).toBe(expected);
  });

  it.each([
    'mode',
    'packages-dir',
    'api-key',
    'db-path',
    'transport',
    'host',
    'hosted-url',
    'hosted-api-key',
    'hosted-api-key-file',
    'custom-dir',
  ])(
    'rejects a bare --%s instead of treating it as unset',
    (name) => {
      expect(parseSetupFlags({ [name]: true })).toEqual({ error: `--${name} needs a value.` });
    }
  );

  it('explains a value that parseArgs swallowed into --non-interactive', () => {
    const parsed = parseSetupFlags({ 'non-interactive': 'hosted' });

    expect(parsed).toEqual({ error: expect.stringContaining('--non-interactive does not take a value') });
    expect('error' in parsed && parsed.error).toContain('"hosted"');
  });
});

describe('setupCommand --non-interactive', () => {
  let root: string;
  let cwd: string;
  let logged: string[];
  let errored: string[];

  beforeEach(() => {
    root = fs.realpathSync(fs.mkdtempSync(path.join(os.tmpdir(), 'setup-flags-')));
    cwd = path.join(root, 'work');
    fs.mkdirSync(cwd);
    logged = [];
    errored = [];
    vi.spyOn(console, 'log').mockImplementation((...args: unknown[]) => void logged.push(args.join(' ')));
    vi.spyOn(console, 'warn').mockImplementation((...args: unknown[]) => void errored.push(args.join(' ')));
    vi.spyOn(console, 'error').mockImplementation((...args: unknown[]) => void errored.push(args.join(' ')));
  });

  afterEach(() => {
    vi.restoreAllMocks();
    fs.rmSync(root, { recursive: true, force: true });
  });

  const run = (options: Partial<SetupOptions>) => setupCommand({ nonInteractive: true, cwd, ...options });
  const envText = () => fs.readFileSync(path.join(cwd, '.env'), 'utf-8');
  const hasEnv = () => fs.existsSync(path.join(cwd, '.env'));

  function stageMetadata(dir: string): string {
    const typeDir = path.join(dir, 'TestPackage', 'TestModel', 'AxTable');
    fs.mkdirSync(typeDir, { recursive: true });
    fs.copyFileSync(path.join(fixturesDir, 'AxTableSample.xml'), path.join(typeDir, 'SampleTable.xml'));
    return dir;
  }

  describe('local mode (unchanged behaviour)', () => {
    it('writes exactly the file and the messages it always wrote', async () => {
      const packagesDir = path.join(root, 'PackagesLocalDirectory');
      fs.mkdirSync(packagesDir);

      const code = await run({ packagesDir, apiKey: API_KEY, dbPath: './d365_index.db' });

      expect(code).toBe(0);
      expect(envText()).toBe(
        [
          '# Generated by `d365-fno-mcp-server setup`',
          'MCP_TRANSPORT=http',
          'MCP_PORT=3000',
          `MCP_API_KEY=${API_KEY}`,
          `D365_PACKAGES_DIR=${packagesDir}`,
          'D365_INDEX_DB_PATH=./d365_index.db',
          '',
        ].join('\n')
      );
      expect(logged).toEqual([
        `Wrote ${path.join(cwd, '.env')}`,
        'Next: run `d365-fno-mcp-server doctor`, then `d365-fno-mcp-server index`.',
      ]);
      expect(errored).toEqual([]);
    });

    it('behaves the same with --mode local given explicitly', async () => {
      const packagesDir = path.join(root, 'PackagesLocalDirectory');
      fs.mkdirSync(packagesDir);

      expect(await run({ mode: 'local', packagesDir, apiKey: API_KEY })).toBe(0);
      expect(parse(envText())).not.toHaveProperty('MCP_HOST');
    });

    it('only warns about a packages folder that does not exist yet, and still exits 0', async () => {
      const missing = path.join(root, 'not-yet');

      expect(await run({ packagesDir: missing, apiKey: API_KEY })).toBe(0);
      expect(errored.join('\n')).toContain(`Warning: packages directory "${missing}" does not exist yet.`);
      expect(parse(envText()).D365_PACKAGES_DIR).toBe(missing);
    });

    it('writes MCP_HOST only when --host is given', async () => {
      const packagesDir = path.join(root, 'PackagesLocalDirectory');
      fs.mkdirSync(packagesDir);

      expect(await run({ packagesDir, apiKey: API_KEY, host: '127.0.0.1' })).toBe(0);
      expect(parse(envText()).MCP_HOST).toBe('127.0.0.1');
      expect(envText().indexOf('MCP_HOST')).toBeLessThan(envText().indexOf('MCP_API_KEY'));
    });

    it.each(['', 'has space', 'a\tb'])('rejects the host %j', async (host) => {
      expect(await run({ packagesDir: root, apiKey: API_KEY, host })).toBe(1);
      expect(errored.join('\n')).toContain('--host must be an address or a host name.');
      expect(hasEnv()).toBe(false);
    });

    it('says where a generated API key was saved, without printing it', async () => {
      expect(await run({ packagesDir: root })).toBe(0);

      const key = parse(envText()).MCP_API_KEY;
      expect(key).toMatch(/^[0-9a-f]{64}$/);
      expect(logged.join('\n')).toContain(`Generated an API key and saved it as MCP_API_KEY in ${path.join(cwd, '.env')}.`);
      expect(logged.join('\n')).not.toContain(key);
    });

    it('stays quiet about the key when one was given', async () => {
      expect(await run({ packagesDir: root, apiKey: API_KEY })).toBe(0);
      expect(logged.join('\n')).not.toContain('Generated an API key');
    });

    it('refuses a key that serve would refuse, such as a placeholder, in plain words', async () => {
      expect(await run({ packagesDir: root, apiKey: 'change-me-'.repeat(5) })).toBe(1);
      expect(errored.join('\n')).toContain('The key is a documentation placeholder');
      expect(errored.join('\n')).not.toContain("'default'");
      expect(hasEnv()).toBe(false);
    });

    it('does not replace a .env that appeared after the check, unless --force is given', async () => {
      fs.writeFileSync(path.join(cwd, '.env'), 'APPEARED=1\n');
      const real = fs.existsSync.bind(fs);
      // The first look, at the start of setup, found no file; the file is there by the time it writes.
      vi.spyOn(fs, 'existsSync').mockImplementation((target) => (String(target) === path.join(cwd, '.env') ? false : real(target)));

      expect(await run({ packagesDir: root, apiKey: API_KEY })).toBe(1);
      expect(errored.join('\n')).toContain('already exists; pass --force to replace it.');
      expect(envText()).toBe('APPEARED=1\n');
    });

    it.skipIf(process.platform === 'win32' || process.getuid?.() === 0)('reports a folder it cannot write in instead of crashing', async () => {
      const readOnly = path.join(root, 'read-only');
      fs.mkdirSync(readOnly);
      fs.chmodSync(readOnly, 0o500);
      try {
        expect(await setupCommand({ nonInteractive: true, cwd: readOnly, packagesDir: root, apiKey: API_KEY })).toBe(1);
        expect(errored.join('\n')).toContain('Setup could not write its files:');
      } finally {
        fs.chmodSync(readOnly, 0o700);
      }
    });

    it('keeps a key that holds a hash intact by quoting it', async () => {
      const key = `${'k'.repeat(35)}#tail`;

      expect(await run({ packagesDir: root, apiKey: key })).toBe(0);
      expect(parse(envText()).MCP_API_KEY).toBe(key);
    });

    it('keeps a packages folder with a space and a hash intact', async () => {
      const packagesDir = path.join(root, 'Dev #1', 'Jo Smith');
      fs.mkdirSync(packagesDir, { recursive: true });

      expect(await run({ packagesDir, apiKey: API_KEY })).toBe(0);
      expect(parse(envText()).D365_PACKAGES_DIR).toBe(packagesDir);
    });

    it('creates the index folder, as before', async () => {
      expect(await run({ packagesDir: root, apiKey: API_KEY, dbPath: './data/index.db' })).toBe(0);
      expect(fs.existsSync(path.join(cwd, 'data'))).toBe(true);
      expect(logged).toContain(`Created index DB directory ${path.join(cwd, 'data')}`);
    });

    it('creates no folder when a value cannot be written to a .env file', async () => {
      const code = await run({ packagesDir: `${root}\nbroken`, apiKey: API_KEY, dbPath: './sub/index.db' });

      expect(code).toBe(1);
      expect(errored.join('\n')).toContain('D365_PACKAGES_DIR cannot be written to a .env file');
      expect(fs.existsSync(path.join(cwd, 'sub'))).toBe(false);
      expect(hasEnv()).toBe(false);
    });

    it('still requires --packages-dir, a long enough key and the http transport', async () => {
      expect(await run({ apiKey: API_KEY })).toBe(1);
      expect(errored.join('\n')).toContain('--packages-dir is required with --non-interactive.');
      expect(await run({ packagesDir: root, apiKey: 'short' })).toBe(1);
      expect(errored.join('\n')).toContain('API key must be at least 32 characters.');
      expect(await run({ packagesDir: root, apiKey: API_KEY, transport: 'stdio' })).toBe(1);
      expect(errored.join('\n')).toContain('Unsupported transport "stdio" (only http is supported).');
      expect(hasEnv()).toBe(false);
    });

    it('refuses to replace a .env without --force, and replaces it with it, owner-only', async () => {
      fs.writeFileSync(path.join(cwd, '.env'), 'OLD=1\n', { mode: 0o644 });

      expect(await run({ packagesDir: root, apiKey: API_KEY })).toBe(1);
      expect(errored.join('\n')).toContain('--force');
      expect(envText()).toBe('OLD=1\n');

      expect(await run({ packagesDir: root, apiKey: API_KEY, force: true })).toBe(0);
      expect(parse(envText()).MCP_API_KEY).toBe(API_KEY);
      if (process.platform !== 'win32') {
        expect(fs.statSync(path.join(cwd, '.env')).mode & 0o777).toBe(0o600);
      }
    });
  });

  describe('--mode', () => {
    it.each(['', 'both', 'Local', 'HOSTED'])('rejects the mode %j', async (mode) => {
      expect(await run({ mode, packagesDir: root, apiKey: API_KEY })).toBe(1);
      expect(errored.join('\n')).toContain('--mode must be "local" or "hosted".');
      expect(hasEnv()).toBe(false);
    });

    it.each([
      [{ packagesDir: '/p' }, '--packages-dir does not apply to --mode hosted.'],
      [{ apiKey: API_KEY }, '--api-key does not apply to --mode hosted.'],
      [{ dbPath: './db' }, '--db-path does not apply to --mode hosted.'],
      [{ transport: 'http' }, '--transport does not apply to --mode hosted.'],
      [{ host: '127.0.0.1' }, '--host does not apply to --mode hosted.'],
    ])('rejects local flag %j in hosted mode', async (flags, message) => {
      expect(await run({ mode: 'hosted', hostedUrl: HOSTED_URL, hostedApiKey: HOSTED_KEY, customDir: root, ...flags })).toBe(1);
      expect(errored.join('\n')).toContain(message);
      expect(hasEnv()).toBe(false);
    });

    it.each([
      [{ hostedUrl: HOSTED_URL }, '--hosted-url applies only to --mode hosted; add --mode hosted.'],
      [{ hostedApiKey: HOSTED_KEY }, '--hosted-api-key applies only to --mode hosted; add --mode hosted.'],
      [{ hostedApiKeyFile: '/k' }, '--hosted-api-key-file applies only to --mode hosted; add --mode hosted.'],
      [{ customDir: '/c' }, '--custom-dir applies only to --mode hosted; add --mode hosted.'],
    ])('rejects hosted flag %j in local mode, which is also the default', async (flags, message) => {
      expect(await run({ packagesDir: root, apiKey: API_KEY, ...flags })).toBe(1);
      expect(errored.join('\n')).toContain(message);
      expect(hasEnv()).toBe(false);
    });
  });

  describe('hosted mode', () => {
    it('writes the three gateway settings, owner-only, in a file the gateway schema accepts', async () => {
      const customDir = stageMetadata(path.join(root, 'Metadata'));
      const keyFile = path.join(root, 'hosted-api-key');
      fs.writeFileSync(keyFile, `${HOSTED_KEY}\n`);

      const code = await run({ mode: 'hosted', hostedUrl: 'https://Hosted.Example.com', hostedApiKeyFile: keyFile, customDir });

      expect(code).toBe(0);
      expect(parse(envText())).toEqual({
        D365_HOSTED_MCP_URL: 'https://hosted.example.com/mcp',
        D365_HOSTED_API_KEY_FILE: keyFile,
        D365_CUSTOM_METADATA_DIR: customDir,
      });
      expect(envText().startsWith('# Generated by `d365-fno-mcp-server setup` (hosted server and custom models)\n')).toBe(true);
      expect(gatewayConfigSchema.safeParse(parse(envText())).success).toBe(true);
      expect(logged).toContain('Next: run `d365-fno-mcp-server doctor`, then `d365-fno-mcp-server gateway`.');
      if (process.platform !== 'win32') {
        expect(fs.statSync(path.join(cwd, '.env')).mode & 0o777).toBe(0o600);
      }
    });

    it('resolves a relative key file and folder against the working folder and writes absolute paths', async () => {
      stageMetadata(path.join(cwd, 'models'));
      fs.writeFileSync(path.join(cwd, 'key.txt'), HOSTED_KEY);

      expect(await run({ mode: 'hosted', hostedUrl: HOSTED_URL, hostedApiKeyFile: 'key.txt', customDir: 'models' })).toBe(0);
      expect(parse(envText())).toMatchObject({
        D365_HOSTED_API_KEY_FILE: path.join(cwd, 'key.txt'),
        D365_CUSTOM_METADATA_DIR: path.join(cwd, 'models'),
      });
    });

    it('stores an inline key and never prints it', async () => {
      const customDir = stageMetadata(path.join(root, 'Metadata'));

      expect(await run({ mode: 'hosted', hostedUrl: HOSTED_URL, hostedApiKey: HOSTED_KEY, customDir })).toBe(0);
      expect(parse(envText()).D365_HOSTED_API_KEY).toBe(HOSTED_KEY);
      expect(logged.join('\n')).not.toContain(HOSTED_KEY);
      expect(errored.join('\n')).not.toContain(HOSTED_KEY);
    });

    it.each([
      [{ hostedApiKey: HOSTED_KEY, customDir: '/c' }, '--hosted-url is required with --mode hosted --non-interactive.'],
      [{ hostedUrl: HOSTED_URL, customDir: '/c' }, '--hosted-api-key-file (or --hosted-api-key) is required with --mode hosted --non-interactive.'],
      [{ hostedUrl: HOSTED_URL, hostedApiKey: HOSTED_KEY }, '--custom-dir is required with --mode hosted --non-interactive.'],
      [
        { hostedUrl: HOSTED_URL, hostedApiKey: HOSTED_KEY, hostedApiKeyFile: '/k', customDir: '/c' },
        'Pass either --hosted-api-key or --hosted-api-key-file, not both.',
      ],
    ])('names the missing or conflicting flag for %j', async (flags, message) => {
      expect(await run({ mode: 'hosted', ...flags })).toBe(1);
      expect(errored.join('\n')).toContain(message);
      expect(hasEnv()).toBe(false);
    });

    it('rejects an insecure URL by flag name', async () => {
      const customDir = stageMetadata(path.join(root, 'Metadata'));

      expect(await run({ mode: 'hosted', hostedUrl: 'http://hosted.example.com/mcp', hostedApiKey: HOSTED_KEY, customDir })).toBe(1);
      expect(errored.join('\n')).toContain('--hosted-url: Use an https:// URL; http:// is accepted only for localhost.');
      expect(hasEnv()).toBe(false);
    });

    it('rejects a key with a space by flag name without quoting it', async () => {
      const customDir = stageMetadata(path.join(root, 'Metadata'));
      const spaced = 'has a space 0123456789';

      expect(await run({ mode: 'hosted', hostedUrl: HOSTED_URL, hostedApiKey: spaced, customDir })).toBe(1);
      expect(errored.join('\n')).toContain('--hosted-api-key: The key can hold only letters, digits and symbols');
      expect(errored.join('\n')).not.toContain(spaced);
    });

    it('rejects a key file that does not exist, naming the flag', async () => {
      const customDir = stageMetadata(path.join(root, 'Metadata'));

      expect(await run({ mode: 'hosted', hostedUrl: HOSTED_URL, hostedApiKeyFile: path.join(root, 'nope'), customDir })).toBe(1);
      expect(errored.join('\n')).toContain('--hosted-api-key-file: There is no file at that path.');
    });

    it('does not repeat a key that was given where the key file belongs', async () => {
      const customDir = stageMetadata(path.join(root, 'Metadata'));

      expect(await run({ mode: 'hosted', hostedUrl: HOSTED_URL, hostedApiKeyFile: HOSTED_KEY, customDir })).toBe(1);
      expect(errored.join('\n')).toContain('--hosted-api-key-file: There is no file at that path.');
      expect(errored.join('\n')).not.toContain(HOSTED_KEY);
      expect(logged.join('\n')).not.toContain(HOSTED_KEY);
    });

    it.skipIf(process.platform === 'win32')('explains a key file path that runs through a file', async () => {
      const customDir = stageMetadata(path.join(root, 'Metadata'));
      const blocker = path.join(root, 'blocker');
      fs.writeFileSync(blocker, 'x');

      expect(await run({ mode: 'hosted', hostedUrl: HOSTED_URL, hostedApiKeyFile: path.join(blocker, 'key'), customDir })).toBe(1);
      expect(errored.join('\n')).toContain('--hosted-api-key-file: Part of that path is a file, not a folder.');
      expect(errored.join('\n')).not.toContain('ENOTDIR');
    });

    it.skipIf(process.platform === 'win32')('explains a custom folder path that runs through a file', async () => {
      const blocker = path.join(root, 'blocker');
      fs.writeFileSync(blocker, 'x');

      expect(await run({ mode: 'hosted', hostedUrl: HOSTED_URL, hostedApiKey: HOSTED_KEY, customDir: path.join(blocker, 'models') })).toBe(1);
      expect(errored.join('\n')).toContain('--custom-dir: Part of that path is a file, not a folder.');
      expect(errored.join('\n')).not.toContain('ENOTDIR');
    });

    it('rejects a custom folder that does not exist, naming the flag', async () => {
      expect(await run({ mode: 'hosted', hostedUrl: HOSTED_URL, hostedApiKey: HOSTED_KEY, customDir: path.join(root, 'nope') })).toBe(1);
      expect(errored.join('\n')).toContain(`--custom-dir: There is no folder at "${path.join(root, 'nope')}".`);
      expect(hasEnv()).toBe(false);
    });

    it('accepts an empty custom folder with a warning, because a new models folder starts empty', async () => {
      const empty = path.join(root, 'EmptyModels');
      fs.mkdirSync(empty);

      expect(await run({ mode: 'hosted', hostedUrl: HOSTED_URL, hostedApiKey: HOSTED_KEY, customDir: empty })).toBe(0);
      expect(errored.join('\n')).toMatch(/Warning: No D365 metadata/);
      expect(parse(envText()).D365_CUSTOM_METADATA_DIR).toBe(empty);
    });
  });
});
