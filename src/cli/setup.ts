import fs from 'fs';
import path from 'path';
import crypto from 'crypto';
import readline from 'readline/promises';
import { stdin, stdout } from 'process';

export interface SetupOptions {
  nonInteractive: boolean;
  packagesDir?: string;
  apiKey?: string;
  dbPath?: string;
  transport?: string;
  cwd?: string;
  /** Replace an existing `.env`; without it setup refuses to overwrite one. */
  force?: boolean;
}

function generateApiKey(): string {
  return crypto.randomBytes(32).toString('hex');
}

function renderEnv(values: {
  packagesDir: string;
  apiKey: string;
  dbPath: string;
  transport: string;
}): string {
  return [
    '# Generated by `d365-fno-mcp-server setup`',
    `MCP_TRANSPORT=${values.transport}`,
    'MCP_PORT=3000',
    `MCP_API_KEY=${values.apiKey}`,
    `D365_PACKAGES_DIR=${values.packagesDir}`,
    `D365_INDEX_DB_PATH=${values.dbPath}`,
    'D365_INDEX_ON_START=0',
    '',
  ].join('\n');
}

async function promptValues(defaults: { dbPath: string; transport: string }) {
  const rl = readline.createInterface({ input: stdin, output: stdout });
  try {
    const packagesDir = (await rl.question('D365 PackagesLocalDirectory path: ')).trim();
    const apiKeyAnswer = (
      await rl.question('MCP API key (>=32 chars, blank to generate): ')
    ).trim();
    const dbPathAnswer = (await rl.question(`Index DB path [${defaults.dbPath}]: `)).trim();
    const transportAnswer = (await rl.question(`Transport (http|stdio) [${defaults.transport}]: `)).trim();

    return {
      packagesDir,
      apiKey: apiKeyAnswer || generateApiKey(),
      dbPath: dbPathAnswer || defaults.dbPath,
      transport: transportAnswer || defaults.transport,
    };
  } finally {
    rl.close();
  }
}

/** Writes a `.env` file, creating the index DB directory when needed. */
export async function setupCommand(options: SetupOptions): Promise<number> {
  const cwd = options.cwd ?? process.cwd();
  const defaultDbPath = options.dbPath ?? './d365_index.db';
  const defaultTransport = options.transport ?? 'http';

  const envPath = path.resolve(cwd, '.env');
  if (fs.existsSync(envPath) && !options.force) {
    console.error(`${envPath} already exists; pass --force to replace it.`);
    return 1;
  }

  let values: { packagesDir: string; apiKey: string; dbPath: string; transport: string };

  if (options.nonInteractive) {
    if (!options.packagesDir) {
      console.error('--packages-dir is required with --non-interactive.');
      return 1;
    }
    values = {
      packagesDir: options.packagesDir,
      apiKey: options.apiKey ?? generateApiKey(),
      dbPath: defaultDbPath,
      transport: defaultTransport,
    };
  } else {
    values = await promptValues({ dbPath: defaultDbPath, transport: defaultTransport });
    if (!values.packagesDir) {
      console.error('A packages directory is required.');
      return 1;
    }
  }

  if (values.apiKey.length < 32) {
    console.error('API key must be at least 32 characters.');
    return 1;
  }
  if (values.transport !== 'http' && values.transport !== 'stdio') {
    console.error(`Unsupported transport "${values.transport}" (expected http or stdio).`);
    return 1;
  }
  if (!fs.existsSync(values.packagesDir)) {
    console.warn(`Warning: packages directory "${values.packagesDir}" does not exist yet.`);
  }

  const dbDir = path.resolve(cwd, path.dirname(values.dbPath));
  if (!fs.existsSync(dbDir)) {
    fs.mkdirSync(dbDir, { recursive: true });
    console.log(`Created index DB directory ${dbDir}`);
  }

  fs.writeFileSync(envPath, renderEnv(values), { mode: 0o600 });
  // `mode` only applies when the file is created; a replaced .env keeps its old mode.
  fs.chmodSync(envPath, 0o600);
  console.log(`Wrote ${envPath}`);
  console.log('Next: run `d365-fno-mcp-server doctor`, then `d365-fno-mcp-server index`.');
  return 0;
}
