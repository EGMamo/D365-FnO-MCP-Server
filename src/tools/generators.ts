import { McpServer } from '@modelcontextprotocol/sdk/server/mcp.js';
import { Database } from 'better-sqlite3';
import { z } from 'zod';
import * as dbUtils from '../indexer/db.js';

export function registerGeneratorTools(server: McpServer, db: Database) {
  server.tool(
    'create_coc_extension',
    'Create an X++ Chain of Command extension class',
    {
      targetClass: z.string(),
      extensionName: z.string(),
      methods: z.array(z.object({
        name: z.string(),
        params: z.string().optional(),
        returnType: z.string().optional()
      }))
    },
    async ({ targetClass, extensionName, methods }) => {
      const obj = dbUtils.getObjectByName(db, targetClass, 'Class') || dbUtils.getObjectByName(db, targetClass, 'Table') || dbUtils.getObjectByName(db, targetClass, 'Form');
      if (!obj) return { content: [{ type: 'text', text: `Target ${targetClass} not found in index. Cannot create CoC safely.` }] };

      let methodsCode = methods.map(m => `    ${m.returnType || 'void'} ${m.name}(${m.params || ''})\n    {\n        next ${m.name}();\n    }`).join('\n\n');

      const template = `[ExtensionOf(classStr(${targetClass}))]\nfinal class ${extensionName}_Extension\n{\n    // Generated by D365 FnO MCP Server\n${methodsCode}\n}`;
      return { content: [{ type: 'text', text: template }] };
    }
  );

  server.tool(
    'create_table_extension',
    'Create a table extension',
    {
      targetTable: z.string(),
      extensionName: z.string(),
      fields: z.array(z.object({ name: z.string(), edt: z.string(), label: z.string().optional() })).optional(),
      indexes: z.array(z.object({ name: z.string(), fields: z.array(z.string()), allowDuplicates: z.boolean().optional() })).optional()
    },
    async ({ targetTable, extensionName, fields: _fields, indexes: _indexes }) => {
      const obj = dbUtils.getObjectByName(db, targetTable, 'Table');
      if (!obj) return { content: [{ type: 'text', text: `Target table ${targetTable} not found.` }] };
      
      const content = `// Table Extension XML structure for ${targetTable}.${extensionName}\n// Implementation details to be scaffolded...`;
      return { content: [{ type: 'text', text: content }] };
    }
  );

  server.tool(
    'create_class_extension',
    'Create X++ class extension boilerplate',
    { targetClass: z.string(), extensionName: z.string() },
    async ({ targetClass, extensionName }) => {
      const template = `[ExtensionOf(classStr(${targetClass}))]\nfinal class ${extensionName}_Extension\n{\n    // Generated by D365 FnO MCP Server\n}`;
      return { content: [{ type: 'text', text: template }] };
    }
  );

  server.tool(
    'generate_xpp_class',
    'Generate standard X++ class',
    {
      className: z.string(),
      extends: z.string().optional(),
      implements: z.array(z.string()).optional(),
      isAbstract: z.boolean().optional(),
      description: z.string().optional()
    },
    async ({ className, extends: ext, implements: impl, isAbstract, description }) => {
      let decl = `${isAbstract ? 'abstract ' : ''}class ${className}`;
      if (ext) decl += ` extends ${ext}`;
      if (impl && impl.length) decl += ` implements ${impl.join(', ')}`;

      const template = `/// <summary>\n/// ${description || 'Generated class'}\n/// </summary>\n${decl}\n{\n}`;
      return { content: [{ type: 'text', text: template }] };
    }
  );

  server.tool(
    'create_runbase_batch',
    'Create RunBaseBatch framework class',
    { className: z.string(), description: z.string(), menuItemName: z.string().optional() },
    async ({ className, description: _description, menuItemName: _menuItemName }) => {
      const template = `class ${className} extends RunBaseBatch\n{\n    // Generated RunBaseBatch framework\n    public container pack() { return []; }\n    public boolean unpack(container _packedClass) { return true; }\n    public void run() {}\n    public static void main(Args _args) {\n        ${className} batch = new ${className}();\n        if (batch.prompt()) batch.runOperation();\n    }\n}`;
      return { content: [{ type: 'text', text: template }] };
    }
  );

  server.tool(
    'create_sys_operation',
    'Create SysOperation framework classes',
    { baseName: z.string(), description: z.string() },
    async ({ baseName, description: _description }) => {
      const result = {
        contract: `[DataContractAttribute]\nclass ${baseName}Contract {\n}`,
        service: `class ${baseName}Service {\n    public void process(${baseName}Contract _contract) {}\n}`,
        controller: `class ${baseName}Controller extends SysOperationServiceController {\n    public static void main(Args _args) {\n        ${baseName}Controller controller = new ${baseName}Controller();\n        controller.startOperation();\n    }\n}`,
        uiBuilder: `class ${baseName}UIBuilder extends SysOperationUIBuilder {\n    public void build() {\n        super();\n    }\n}`
      };
      return { content: [{ type: 'text', text: JSON.stringify(result, null, 2) }] };
    }
  );
}
